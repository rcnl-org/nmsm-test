% This function returns the known values of the MTP test fixtures in
% tests/data/mtp, so tests share one source of truth instead of repeating
% numbers. MtpFixtureTest checks that the fixture files still match these.
%
% The fixtures are the reduced-muscle tutorial problem from
% nmsm-tutorial/Step-4-Muscle-Tendon-Personalization (see
% tests/data/mtp/README.md).
%
% () -> (struct)

function values = mtpFixtureValues()
values.modelFileName = "UF_Subject_3_reduced_muscles.osim";

% Coordinates whose moments MTP tracks, and the muscles spanning them.
% These nine are the only muscles in the model.
values.coordinateNames = ["hip_flexion_r", "knee_angle_r", "ankle_angle_r"];
values.muscleNames = ["bflh_r", "bfsh_r", "gasmed_r", "glmax2_r", ...
    "iliacus_r", "recfem_r", "soleus_r", "tibant_r", "vasmed_r"];

% Muscle properties in the model, in muscleNames order
values.maxIsometricForce = [4000, 1000, 4500, 4500, 2500, 3000, 9500, ...
    2000, 9000]; % N
values.optimalFiberLength = [0.096409643963095468, ...
    0.11006278769212309, 0.052321270542681951, 0.16334895528432036, ...
    0.11227187587425631, 0.075976134857518668, 0.045261359759536893, ...
    0.070527947382536968, 0.096554317358358274]; % m
values.tendonSlackLength = [0.32126009522922916, 0.1055896469967792, ...
    0.40904598253202668, 0.070632453645614698, 0.10123501165330601, ...
    0.44894341871124266, 0.28468970693576201, 0.2483048699582821, ...
    0.19939690504339133]; % m
values.pennationAngle = [0.17591823000000001, 0.26422317000000001, ...
    0.16568155000000001, 0.36738206000000001, 0.27991397000000001, ...
    0.21701490000000001, 0.38142888000000003, 0.19518281000000001, ...
    0.42222252999999998]; % rad

% Muscle groups (model ObjectGroups) used by the settings files
values.collectedEmgChannelGroups = struct( ...
    "GlutMaxLat", "glmax2_r", ...
    "RecFem", "recfem_r", ...
    "BicFemLong", "bflh_r", ...
    "BicFemShort", "bfsh_r", ...
    "VastMed", "vasmed_r", ...
    "GasMed", "gasmed_r", ...
    "Sol", "soleus_r", ...
    "TibAnt", "tibant_r");
values.missingEmgChannelGroups = struct( ...
    "HipFlexorsMissingEMGChannelGroup", "iliacus_r");
values.activationGroups = struct( ...
    "HipFlexorsActivationGroupR", "iliacus_r", ...
    "GlutmaxActivationGroupR", "glmax2_r", ...
    "HamslatActivationGroupR", ["bflh_r", "bfsh_r"], ...
    "VasActivationGroupR", "vasmed_r", ...
    "GasActivationGroupR", "gasmed_r");
values.normalizedFiberLengthGroups = struct( ...
    "GlutmaxNormalizedFiberLengthGroupR", "glmax2_r", ...
    "HamsNormalizedFiberLengthGroupR", "bflh_r", ...
    "VasNormalizedFiberLengthGroupR", "vasmed_r", ...
    "GasNormalizedFiberLengthGroupR", "gasmed_r");

% One gait trial. IK, ID and muscle analysis share one time grid; EMG has
% the same spacing with 19 extra frames on each side for the
% electromechanical delay and activation dynamics.
values.trialName = "gait_1";
values.numFrames = 101;
values.timeRange = [0.5, 1.6]; % s
values.numEmgPaddingFrames = 19;
values.emgTimeRange = [0.291, 1.809]; % s
values.numEmgChannels = 28;

% Passive trials for Muscle-Tendon Length Initialization: 101 frames each
values.passiveTrialNames = ["Thelen_AnklePassive_01", ...
    "Thelen_AnklePassive_02", "Thelen_AnklePassive_03", ...
    "Thelen_AnklePassive_04", "Thelen_HipPassive_01", ...
    "Thelen_HipPassive_02", "Thelen_HipPassive_03", ...
    "Thelen_HipPassive_04", "Thelen_KneePassive_01", ...
    "Thelen_KneePassive_02", "Thelen_KneePassive_03", ...
    "Thelen_KneePassive_04"];
values.passiveCoordinateNames = ["hip_flexion_r", "hip_adduction_r", ...
    "hip_rotation_r", "knee_angle_r", "ankle_angle_r", "subtalar_angle_r"];
values.numPassiveFrames = 101;

% MTP's starting values on candidate-1.5.4 (MuscleTendonPersonalization
% prepareInitialValues), the same for every muscle: electromechanical delay
% (s x 10), activation time constant (s x 100), activation nonlinearity,
% EMG scale factor, optimal fiber length and tendon slack length scale
% factors.
values.initialGuess = struct("electromechanicalDelays", 0.5, ...
    "activationTimeConstants", 1.5, ...
    "activationNonlinearityConstants", 0.05, "emgScaleFactors", 0.5, ...
    "optimalFiberLengthScaleFactors", 1, ...
    "tendonSlackLengthScaleFactors", 1);

% Synthetic known-truth problems (tests/data/mtp/synthetic). They use
% UF_Subject_3_reduced_muscles_synthetic.osim, the fixture model with some
% muscles' optimal fiber and tendon slack lengths adjusted so every
% normalized fiber length is within MTP's 0.3 to 1.3 limits at the
% starting values. Each case's inverse dynamics moments were computed by
% MTP's own forward model at these per-muscle values (muscleNames order),
% so MTP started from initialGuess should find them again. Parameters a
% case does not optimize are at initialGuess. iliacus_r (5th) has no EMG
% without synergy extrapolation, so its activation parameters cannot be
% identified and stay at initialGuess in both cases. Tendon slack length
% changes are kept to 1%: for long-tendon muscles like gasmed_r, 1% moves
% the normalized fiber length by about 0.08.
values.synthetic.modelFileName = "UF_Subject_3_reduced_muscles_synthetic.osim";
initial = structfun(@(x) repmat(x, 1, 9), values.initialGuess, ...
    "UniformOutput", false);
emgScale = initial;
emgScale.emgScaleFactors = [0.35, 0.6, 0.45, 0.3, 0.5, 0.55, 0.4, ...
    0.65, 0.38];
values.synthetic.emgScale = emgScale;
all = emgScale;
all.electromechanicalDelays = [0.3, 0.6, 0.4, 0.7, 0.5, 0.35, 0.65, ...
    0.45, 0.55];
all.activationTimeConstants = [1.2, 1.8, 1.4, 2.0, 1.5, 1.6, 1.3, ...
    1.9, 1.7];
all.activationNonlinearityConstants = [0.1, 0.05, 0.15, 0.08, 0.05, ...
    0.12, 0.2, 0.06, 0.1];
all.optimalFiberLengthScaleFactors = [1.05, 0.95, 1.1, 0.92, 1, 1.08, ...
    0.97, 1.03, 0.94];
all.tendonSlackLengthScaleFactors = [0.99, 1.01, 0.99, 1.01, 1, 0.99, ...
    1.01, 0.99, 1.01];
values.synthetic.all = all;
% Same true values on two gait trials (tests/data/mtp/rebuilt), so the
% parameters that trade off on one trial must also fit a second one.
values.synthetic.twoTrials = all;

% Synthetic Muscle-Tendon Length Initialization case: passive moments
% computed by MTLI's forward model for the fixture model (not the
% synthetic one) at these optimal fiber and tendon slack length scale
% factors, with maximum isometric force and muscle stress fixed.
values.synthetic.passive.optimalFiberLengthScaleFactors = [1.05, 0.95, ...
    1.08, 0.93, 1.04, 0.96, 1.06, 0.94, 1.02];
values.synthetic.passive.tendonSlackLengthScaleFactors = [0.98, 1.02, ...
    0.99, 1.01, 0.97, 1.03, 0.99, 1.01, 1];
values.synthetic.passive.maximumMuscleStressScaleFactor = 1;

% The tutorial's own run (MTPResultsV1 in nmsm-tutorial) matched the
% inverse dynamics moments with these RMS errors, in Nm, for
% coordinateNames, using the synergy extrapolation model's moments.
values.tutorialMomentRms = [5.78, 6.515, 7.452];
end
